type FingerprintSource = Readonly<Record<string, unknown>>

const normalizedPath = (value: string): string => value.replaceAll("\\", "/")

/**
 * Identifies compiler-generated output inside the pinned Expo checkout.
 *
 * Root and plugin `build/` directories intentionally remain fingerprinted: they contain the
 * JavaScript config-plugin implementation that produces native inputs. Only platform compiler
 * products are excluded.
 */
export const isGeneratedExpoNativeOutput = (filePath: string): boolean => {
  const value = normalizedPath(filePath)
  if (!/\/packages\/(?:@expo\/[^/]+|expo(?:-[^/]+)?|unimodules-[^/]+|precompile)\//.test(value)) {
    return false
  }
  return (
    /\/(?:android|ios)\/(?:build|\.cxx)\//.test(value) ||
    /\/apple\/(?:Products|\.DerivedData)\//.test(value) ||
    /\/packages\/precompile\/\.build\//.test(value)
  )
}

const stableValue = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(stableValue)
  if (typeof value !== "object" || value === null) return value
  return Object.fromEntries(
    Object.entries(value)
      .toSorted(([left], [right]) => left.localeCompare(right))
      .map(([key, entry]) => [key, stableValue(entry)]),
  )
}

const nativeExpoConfig = (contents: string): string => {
  const parsed = JSON.parse(contents) as unknown
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) return contents
  const config = { ...(parsed as Record<string, unknown>) }
  if (typeof config.extra === "object" && config.extra !== null && !Array.isArray(config.extra)) {
    const extra = { ...(config.extra as Record<string, unknown>) }
    // These values select the JavaScript resolution cohort and are embedded by the repack. They
    // never alter the native project generated by the compatibility app's reviewed plugins.
    delete extra.betterNativeMode
    delete extra.betterNativeBuildId
    config.extra = extra
  }
  return JSON.stringify(stableValue(config))
}

/**
 * Produces the native-only source closure shared by upstream and candidate builds.
 */
export const canonicalNativeFingerprintSources = (
  sources: ReadonlyArray<object>,
): ReadonlyArray<FingerprintSource> =>
  sources
    .map((source) => source as FingerprintSource)
    .filter(
      (source) =>
        typeof source.filePath !== "string" || !isGeneratedExpoNativeOutput(source.filePath),
    )
    .map((source) => {
      if (
        source.type !== "contents" ||
        source.id !== "expoConfig" ||
        typeof source.contents !== "string"
      ) {
        return source
      }
      const { hash: _derivedHash, ...rest } = source
      return { ...rest, contents: nativeExpoConfig(source.contents) }
    })
    .toSorted((left, right) => JSON.stringify(left).localeCompare(JSON.stringify(right)))

/** Encodes a canonical native source closure for the harness product digester. */
export const nativeClosureFingerprintInput = (
  sources: ReadonlyArray<FingerprintSource>,
): Uint8Array =>
  new TextEncoder().encode(JSON.stringify(canonicalNativeFingerprintSources(sources)))
